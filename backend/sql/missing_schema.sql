-- 5. Fix infinite recursion in ride_history / ride_history_participants RLS policies.
-- The old participants policy queried ride_history, whose policy queried ride_history_participants,
-- causing "infinite recursion detected in policy for relation 'ride_history_participants'".
CREATE OR REPLACE FUNCTION public.is_ride_history_participant(p_history_id uuid, p_user_id uuid)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.ride_history_participants
    WHERE ride_history_id = p_history_id
      AND user_id = p_user_id
  );
$$;

DROP POLICY IF EXISTS "Users can view their ride history" ON public.ride_history;
CREATE POLICY "Users can view their ride history" ON public.ride_history
  FOR SELECT TO authenticated
  USING (
    public.is_ride_history_participant(ride_history.id, auth.uid())
  );

DROP POLICY IF EXISTS "Users can view history participants" ON public.ride_history_participants;
CREATE POLICY "Users can view history participants" ON public.ride_history_participants
  FOR SELECT TO authenticated
  USING (
    user_id = auth.uid()
    OR public.is_ride_history_participant(ride_history_participants.ride_history_id, auth.uid())
  );

GRANT EXECUTE ON FUNCTION public.is_ride_history_participant(uuid, uuid) TO authenticated;

-- 6. get_party_route_savings RPC (exists in ride_history.sql but was never deployed;
-- used by LivePartyScreen.buildSavingsMessage, which currently swallows the 404)
DROP FUNCTION IF EXISTS public.get_party_route_savings(uuid);
CREATE OR REPLACE FUNCTION public.get_party_route_savings(
  p_party_id uuid
)
RETURNS TABLE (
  distance_saved_km double precision,
  time_saved_minutes double precision,
  baseline_km double precision,
  optimized_km double precision,
  baseline_minutes double precision,
  optimized_minutes double precision
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  RETURN QUERY
  SELECT
    p.route_distance_saved_km,
    p.route_time_saved_minutes,
    p.route_baseline_km,
    p.route_optimized_km,
    p.route_baseline_minutes,
    p.route_optimized_minutes
  FROM public.parties p
  WHERE p.id = p_party_id
    AND public.can_user_view_party_members(p.id);
END;
$$;

GRANT EXECUTE ON FUNCTION public.get_party_route_savings(uuid) TO authenticated;