-- 1. profiles.student_type column (hosteller / dayscholar)
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS student_type text null;

-- 2. ratings table
CREATE TABLE IF NOT EXISTS public.ratings (
  id bigint generated by default as identity not null,
  rater_id uuid not null,
  rated_user_id uuid not null,
  party_id uuid not null,
  score integer not null check (score between 1 and 5),
  comment text null,
  created_at timestamp with time zone not null default timezone('utc'::text, now()),
  constraint ratings_pkey primary key (id),
  constraint ratings_rater_id_fkey foreign key (rater_id) references public.profiles(id) on delete cascade,
  constraint ratings_rated_user_id_fkey foreign key (rated_user_id) references public.profiles(id) on delete cascade,
  constraint ratings_party_id_fkey foreign key (party_id) references public.parties(id) on delete cascade,
  constraint ratings_unique_per_rater unique (rater_id, rated_user_id, party_id)
) TABLESPACE pg_default;

CREATE INDEX IF NOT EXISTS idx_ratings_rated_user ON public.ratings(rated_user_id);
CREATE INDEX IF NOT EXISTS idx_ratings_rater ON public.ratings(rater_id);

ALTER TABLE public.ratings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Anyone can read ratings" ON public.ratings;
CREATE POLICY "Anyone can read ratings" ON public.ratings
  FOR SELECT TO authenticated
  USING (true);

DROP POLICY IF EXISTS "Users can insert their own ratings" ON public.ratings;
CREATE POLICY "Users can insert their own ratings" ON public.ratings
  FOR INSERT TO authenticated
  WITH CHECK (rater_id = auth.uid());

